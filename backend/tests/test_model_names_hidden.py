import asyncio
import re
import unittest
from unittest.mock import AsyncMock, MagicMock, patch

from fastapi.testclient import TestClient

from app.core.config import settings
from app.main import app
from app.services.azure_image_client import azure_image_client


class ModelNamesHiddenTests(unittest.TestCase):
    def setUp(self):
        self.client = TestClient(app)
        self.addCleanup(self.client.close)
        self.addCleanup(app.dependency_overrides.clear)
        self._reset_azure_client()
        self.addCleanup(self._reset_azure_client)

        # Forbidden model name tokens that should NEVER be visible to users in status messages
        self.forbidden_patterns = [
            re.compile(r"gpt-image", re.IGNORECASE),
            re.compile(r"flare", re.IGNORECASE),
            re.compile(r"sunburst", re.IGNORECASE),
            re.compile(r"flux1", re.IGNORECASE),
            re.compile(r"safetensors", re.IGNORECASE),
            re.compile(r"dall-e", re.IGNORECASE),
        ]

    def _reset_azure_client(self):
        for w in azure_image_client.workers:
            w.active_job_id = None
            w.active_job_start = 0.0
            w.last_dispatch_time = 0.0
            w.cooldown_until = 0.0
            if w.lock.locked():
                w.lock.release()
        azure_image_client._waiting_jobs.clear()

    def _assert_no_model_names(self, text: str):
        for pattern in self.forbidden_patterns:
            self.assertIsNone(
                pattern.search(text),
                f"Forbidden model pattern '{pattern.pattern}' found in text: '{text}'",
            )

    def test_queue_status_does_not_leak_model_names(self):
        status = azure_image_client.get_queue_status()
        self.assertIn("active_jobs", status)
        self.assertIn("total_workers", status)
        self.assertIn("status_text", status)
        self._assert_no_model_names(status["status_text"])

        # active_workers should be an integer count, not a list of raw deployment names
        self.assertIsInstance(status.get("active_workers"), int)

    def test_api_today_endpoint_engine_name_sanitized(self):
        response = self.client.get("/api/trends/today")
        self.assertEqual(response.status_code, 200)
        data = response.json()
        self.assertIn("engine_name", data)
        self._assert_no_model_names(data["engine_name"])
        self.assertIn(data["engine_name"], ["Cloud Studio", "Local GPU Studio"])

    def test_api_queue_status_endpoint_no_model_leak(self):
        with patch.object(settings, "ENGINE", "azure"):
            response = self.client.get("/api/trends/queue-status")
            self.assertEqual(response.status_code, 200)
            data = response.json()
            self._assert_no_model_names(data.get("status_text", ""))
            self.assertIsInstance(data.get("active_workers"), int)

        with patch.object(settings, "ENGINE", "flux"):
            response = self.client.get("/api/trends/queue-status")
            self.assertEqual(response.status_code, 200)
            data = response.json()
            self._assert_no_model_names(data.get("status_text", ""))
            self.assertIsInstance(data.get("active_workers"), int)

    def test_generation_processing_callback_hides_model_names(self):
        """
        Verify that processing status callback events generated by AzureImageClient
        do not include raw model names in their messages.
        """
        captured_messages = []

        async def run_simulated_dispatch():
            def capture_status(event):
                if "message" in event:
                    captured_messages.append(event["message"])

            with patch.object(
                azure_image_client,
                "_execute_single_attempt",
                new=AsyncMock(return_value=("https://example.com/img.png", "https://example.com/thumb.webp")),
            ):
                with patch.object(settings, "AZURE_AI_API_KEY", "mock-key"):
                    await azure_image_client.generate_portrait(
                        photo_bytes=b"fake-bytes",
                        prompt="cyberpunk portrait",
                        on_status=capture_status,
                    )

        asyncio.run(run_simulated_dispatch())

        self.assertGreater(len(captured_messages), 0, "Expected at least one status update callback")
        for msg in captured_messages:
            self._assert_no_model_names(msg)
            self.assertIn("studio quality", msg)

    def test_generation_spacing_wait_callback_hides_model_names(self):
        """
        Verify that spacing_wait status callback events do not leak worker names.
        """
        import time
        captured_events = []

        async def run_spacing_dispatch():
            def capture_status(event):
                captured_events.append(event)

            # Set worker 0 to have dispatched 28.5 seconds ago (spacing is 30s at 2.0 RPM, so ready in 1.5s <= 2.5s)
            azure_image_client.workers[0].last_dispatch_time = time.time() - 28.5
            # Set remaining workers to have high cooldown so worker 0 is chosen
            for w in azure_image_client.workers[1:]:
                w.cooldown_until = time.time() + 120.0

            with patch("app.services.azure_image_client.asyncio.sleep", new=AsyncMock()):
                with patch.object(
                    azure_image_client,
                    "_execute_single_attempt",
                    new=AsyncMock(return_value=("https://example.com/img.png", "https://example.com/thumb.webp")),
                ):
                    with patch.object(settings, "AZURE_AI_API_KEY", "mock-key"):
                        await azure_image_client.generate_portrait(
                            photo_bytes=b"fake-bytes",
                            prompt="cyberpunk portrait",
                            on_status=capture_status,
                        )

        asyncio.run(run_spacing_dispatch())

        spacing_events = [e for e in captured_events if e.get("type") == "spacing_wait"]
        self.assertGreater(len(spacing_events), 0, "Expected at least one spacing_wait event")
        for event in spacing_events:
            msg = event.get("message", "")
            self._assert_no_model_names(msg)
            self.assertIn("Optimal quality pacing", msg)

    def test_generation_retry_failover_callback_hides_model_names(self):
        """
        Verify that 429 throttling failover status messages do not expose model names.
        """
        captured_events = []
        from fastapi import HTTPException

        async def run_retry_dispatch():
            def capture_status(event):
                captured_events.append(event)

            # Attempt 1 fails with 429 containing raw model name in detail, attempt 2 succeeds on next worker
            attempt_side_effects = [
                HTTPException(status_code=429, detail="Rate limit exceeded on gpt-image-2.5-flare"),
                ("https://example.com/img.png", "https://example.com/thumb.webp"),
            ]

            with patch("app.services.azure_image_client.asyncio.sleep", new=AsyncMock()):
                with patch.object(
                    azure_image_client,
                    "_execute_single_attempt",
                    new=AsyncMock(side_effect=attempt_side_effects),
                ):
                    with patch.object(settings, "AZURE_AI_API_KEY", "mock-key"):
                        await azure_image_client.generate_portrait(
                            photo_bytes=b"fake-bytes",
                            prompt="cyberpunk portrait",
                            on_status=capture_status,
                        )

        asyncio.run(run_retry_dispatch())

        retry_events = [e for e in captured_events if e.get("type") == "retrying"]
        self.assertGreater(len(retry_events), 0, "Expected at least one retry event")
        for event in retry_events:
            msg = event.get("message", "")
            self._assert_no_model_names(msg)
            self.assertIn("Rerouting to next available studio engine", msg)

    def test_generation_generic_retry_callback_hides_model_names(self):
        """
        Verify that generic exception retries do not leak raw exception messages containing model names.
        """
        captured_events = []

        async def run_generic_retry_dispatch():
            def capture_status(event):
                captured_events.append(event)

            # Attempt 1 raises generic Exception mentioning internal model deployment, attempt 2 succeeds
            attempt_side_effects = [
                RuntimeError("Deployment 'gpt-image-2.5-flare' connection reset"),
                ("https://example.com/img.png", "https://example.com/thumb.webp"),
            ]

            with patch("app.services.azure_image_client.asyncio.sleep", new=AsyncMock()):
                with patch.object(
                    azure_image_client,
                    "_execute_single_attempt",
                    new=AsyncMock(side_effect=attempt_side_effects),
                ):
                    with patch.object(settings, "AZURE_AI_API_KEY", "mock-key"):
                        await azure_image_client.generate_portrait(
                            photo_bytes=b"fake-bytes",
                            prompt="cyberpunk portrait",
                            on_status=capture_status,
                        )

        asyncio.run(run_generic_retry_dispatch())

        retry_events = [e for e in captured_events if e.get("type") == "retrying"]
        self.assertGreater(len(retry_events), 0, "Expected at least one retry event")
        for event in retry_events:
            msg = event.get("message", "")
            self._assert_no_model_names(msg)
            self.assertIn("Encountered temporary error", msg)


if __name__ == "__main__":
    unittest.main()
